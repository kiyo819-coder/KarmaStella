function scCalcNenchuu(year, month, day) {
  const risshun = SC_RISSHUN[year] || 4;
  let y = (month === 1 || (month === 2 && day < risshun)) ? year - 1 : year;
  const idx = ((y - 4) % 60 + 60) % 60;
  return scKanshiFromIndex(idx);
}

function scCalcGetchuu(year, month, day, nenKan) {
  let monthIdx;
  if (month === 1) {
    monthIdx = day < SC_SEKKI[11] ? 10 : 11;
  } else if (month === 2) {
    monthIdx = day < SC_SEKKI[0] ? 11 : 0;
  } else {
    const base = month - 2;
    monthIdx = day < SC_SEKKI[base] ? base - 1 : base;
  }
  if (monthIdx < 0) monthIdx = 11;
  return { kan: (SC_MONTH_KAN[nenKan] || SC_MONTH_KAN['甲'])[monthIdx], shi: SC_MONTH_SHI[monthIdx] };
}

function calcMeishiki(year, month, day) {
  const nicchuu  = scCalcNicchuu(year, month, day);
  const nenchuu  = scCalcNenchuu(year, month, day);
  const getchuu  = scCalcGetchuu(year, month, day, nenchuu.kan);
  const gogyou   = { '木':0,'火':0,'土':0,'金':0,'水':0 };
  [nenchuu.kan, getchuu.kan, nicchuu.kan].forEach(k => gogyou[SC_KAN_ELEMENT[k]]++);
  [nenchuu.shi, getchuu.shi, nicchuu.shi].forEach(s => gogyou[SC_SHI_ELEMENT[s]]++);
  return { nenchuu, getchuu, nicchuu, nichkan: nicchuu.kan, gogyou };
}

