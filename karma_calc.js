// ── 節入り日を取得（テーブルにない年は概算フォールバック）──
const SETSU_DEFAULT = [0,6,4,6,5,6,6,8,8,8,9,8,8];
function getSetsuiri(year, month) {
  const tbl = SETSUIRI[year] || SETSU_DEFAULT;
  return tbl[month];
}

// ── 本命星（修正版 v2.1）──
function calcHonmeiSei(year, month, day) {
  const risshun = getSetsuiri(year, 2);
  const y = (month === 1 || (month === 2 && day < risshun)) ? year - 1 : year;
  let sum = String(y).split('').reduce((s, d) => s + parseInt(d,10), 0);
  while (sum > 9) sum = String(sum).split('').reduce((s, d) => s + parseInt(d,10), 0);
  let sei = 11 - sum;
  if (sei > 9) sei -= 9;
  if (sei <= 0) sei += 9;
  return sei;
}

// ── 月命星（精密版）──
function calcTsukiMeiSei(honmeiSei, birthYear, birthMonth, birthDay) {
  const setsuDay = getSetsuiri(birthYear, birthMonth);
  let m = birthMonth;
  let y = birthYear;
  if (birthDay < setsuDay) {
    m = birthMonth - 1;
    if (m === 0) { m = 12; y = birthYear - 1; }
  }
  const monthIndex = (m >= 2) ? m - 1 : 12;
  const baseMap = {1:8, 4:8, 7:8, 2:5, 5:5, 8:5, 3:2, 6:2, 9:2};
  const base = baseMap[honmeiSei];
  let sei = base - (monthIndex - 1);
  while (sei <= 0) sei += 9;
  return sei;
}

// ── 傾斜宮（精密版）──
// 根拠: 洛書九宮の数学的逆引き（九星気学万年暦準拠）
// 定義: 月命星(tsuki)を中宮(5)に置いた月盤で、本命星(honmei)が入る宮番号を算出
// 月盤の各宮xの数字: ((x-1+(tsuki-5))%9+9)%9+1
// 本命星が入る宮baseの逆引き: base = ((honmei-1-(tsuki-5))%9+9)%9+1
const KYUU_NAME = {1:'坎宮', 2:'坤宮', 3:'震宮', 4:'巽宮', 5:'中宮', 6:'乾宮', 7:'兌宮', 8:'艮宮', 9:'離宮'};
function calcKeishaSei(honmeiSei, tsukiMeiSei) {
  const base = ((honmeiSei - 1 - (tsukiMeiSei - 5)) % 9 + 9) % 9 + 1;
  return base;
}

